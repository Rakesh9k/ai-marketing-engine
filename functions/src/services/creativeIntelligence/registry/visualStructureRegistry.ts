/** Register all visual structures in the global OntologyRegistry */
export function registerVisualStructures() {
  rawVisualStructures.forEach((vs) => {
    const item = {
      type: 'visual_structure',
      id: vs.id || vs.slug,
      slug: vs.slug || vs.id,
      ...vs,
    };
    OntologyRegistry.register('visual_structure', item as any);
  });
}

