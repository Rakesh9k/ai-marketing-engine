import type { BrandCheckResult, BrandGovernanceIssue, CreativeGovernanceInput } from "../../types/governance";

export class CreativeBrandIntegrationService {
  /**
   * Validates creative against authoritative Business Brain brand positioning,
   * brand voice, prohibited terms, preferred terms, visual identity, and cultural guidelines.
   */
  public evaluateBrand(input: CreativeGovernanceInput): BrandCheckResult {
    const issues: BrandGovernanceIssue[] = [];

    const brandPositioning = input.businessContext.brandPositioning;
    const restrictions = input.businessContext.restrictions || [];
    const culturalContext = input.businessContext.culturalContext;

    const getStr = (val: any): string => {
      if (!val) return "";
      if (typeof val === "string") return val;
      return val.content || "";
    };

    const copyText = [
      getStr(input.copy?.headline),
      getStr(input.copy?.supportingCopy),
      getStr(input.copy?.cta),
      getStr(input.copy?.offerCopy),
      input.strategy.hook?.openingFunction || input.strategy.hook?.illustrativeExample || (input.strategy.hook as any)?.text || "",
    ]
      .join(" ")
      .toLowerCase();

    let voiceCompliant = true;
    let positioningCompliant = true;
    let visualIdentityCompliant = true;

    // 1. Prohibited Brand Treatments / Prohibited Words
    if (brandPositioning?.prohibitedTreatments) {
      for (const prohibited of brandPositioning.prohibitedTreatments) {
        if (copyText.includes(prohibited.toLowerCase())) {
          voiceCompliant = false;
          issues.push({
            code: "PROHIBITED_BRAND_TREATMENT",
            message: `Creative text contains prohibited brand treatment: '${prohibited}'`,
            severity: "ERROR",
            element: "copyText",
            policyRule: `brandPositioning.prohibitedTreatments contains '${prohibited}'`,
          });
        }
      }
    }

    // 2. Business Restrictions Check (Claim, Style, Legal, Brand)
    for (const restriction of restrictions) {
      if (restriction.type === "BRAND" || restriction.type === "STYLE" || restriction.type === "LEGAL") {
        const rawRule = restriction.rule.toLowerCase();
        const targetPhrase = rawRule.replace(/^(never claim to be|do not use|never say|prohibit|do not claim)\s+/i, "").trim();
        if (copyText.includes(rawRule) || (targetPhrase.length > 0 && copyText.includes(targetPhrase))) {
          positioningCompliant = false;
          issues.push({
            code: "BRAND_RESTRICTION_VIOLATION",
            message: `Creative violates business restriction rule: '${restriction.rule}'`,
            severity: restriction.severity === "HARD" ? "ERROR" : "WARNING",
            element: "restrictionCheck",
            policyRule: restriction.rule,
          });
        }
      }
    }

    // 3. Brand Logo Usage Verification (for Visual Assets)
    if (input.assets && input.assets.length > 0) {
      const logoAsset = input.assets.find((a) => (a as any).compositionRole === "BRAND_HEADER" || (a.type as string) === "LOGO" || (a.role as string) === "BRANDING");
      if (logoAsset && logoAsset.source === "GENERATED") {
        visualIdentityCompliant = false;
        issues.push({
          code: "GENERATED_LOGO_VIOLATION",
          message: "Brand logo must come from verified business asset, never hallucinated/generated by image models",
          severity: "ERROR",
          element: "logoAsset",
        });
      }
    }

    // 4. Cultural & Stereotype Constraints
    if (culturalContext?.prohibitedStereotypes) {
      for (const stereotype of culturalContext.prohibitedStereotypes) {
        if (copyText.includes(stereotype.toLowerCase())) {
          voiceCompliant = false;
          issues.push({
            code: "CULTURAL_STEREOTYPE_VIOLATION",
            message: `Creative contains prohibited cultural stereotype: '${stereotype}'`,
            severity: "ERROR",
            element: "culturalContext",
          });
        }
      }
    }

    const hasErrors = issues.some((i) => i.severity === "ERROR");
    const hasWarnings = issues.some((i) => i.severity === "WARNING");

    let status: "PASS" | "REVIEW" | "FAIL" = "PASS";
    if (hasErrors) {
      status = "FAIL";
    } else if (hasWarnings) {
      status = "REVIEW";
    }

    return {
      status,
      voiceCompliant,
      positioningCompliant,
      visualIdentityCompliant,
      issues,
      policyVersion: "2026.10.07-brand-v1",
    };
  }
}
